import type { ColumnType, Generated, Insertable, Selectable, Updateable } from "kysely";

/** Kysely table types; must match migrations/. */

type CreatedAt = ColumnType<Date, Date | undefined, never>;

export type Role = "admin" | "member";
export type AuthType = "none" | "bearer" | "header";
export type ServerStatus = "connected" | "unreachable" | "unknown";
export type AuditOutcome =
  "success" | "tool_error" | "timeout" | "unreachable" | "rejected" | "denied" | "held";
/** "dashboard": actions taken in the dashboard itself, e.g. creating a store. */
export type AuditSource = "mcp" | "chat" | "dashboard";

export interface UsersTable {
  id: Generated<string>;
  email: string;
  name: string;
  role: Role;
  created_at: CreatedAt;
  disabled_at: Date | null;
  password_hash: string | null;
}

export interface ApiKeysTable {
  id: Generated<string>;
  user_id: string;
  name: string;
  prefix: string;
  key_hash: Buffer;
  created_at: CreatedAt;
  last_used_at: Date | null;
  revoked_at: Date | null;
}

/** Cached tools/list result for one upstream (MCP Tool objects, unmodified). */
export type ToolsCache = ColumnType<unknown[] | null, string | null, string | null>;

export interface McpServersTable {
  id: Generated<string>;
  slug: string;
  name: string;
  url: string;
  enabled: Generated<boolean>;
  auth_type: Generated<AuthType>;
  auth_header_name: string | null;
  /** Whether the credential store (a Kubernetes Secret) holds a value for this server. */
  has_credential: Generated<boolean>;
  timeout_ms: Generated<number>;
  /** Admin-declared: every tool of this server only reads, whatever its `readOnlyHint` says. */
  read_only: Generated<boolean>;
  status: Generated<ServerStatus>;
  last_error: string | null;
  last_checked_at: Date | null;
  tools_cache: ToolsCache;
  tools_cached_at: Date | null;
  /** Set when the provisioner owns this row (a store's or hosted server's MCP endpoint). */
  managed_by: ManagedBy | null;
  created_at: CreatedAt;
  updated_at: Generated<Date>;
}

export type ManagedBy = "store" | "hosted";
export type StoreKind = "default" | "provisioned";
export type StoreStatus = "provisioning" | "ready" | "failed" | "deleting";

export interface StoresTable {
  id: Generated<string>;
  slug: string;
  name: string;
  owner_id: string | null;
  kind: Generated<StoreKind>;
  status: Generated<StoreStatus>;
  /** The last provisioning step reached (shown while provisioning, and in failures). */
  step: string | null;
  reason: string | null;
  namespace: string | null;
  /** Public storefront URL. */
  url: string | null;
  server_id: string | null;
  deadline_at: Date | null;
  created_at: CreatedAt;
  updated_at: Generated<Date>;
}

export type HostedTransport = "http" | "stdio";
export type HostedLibc = "glibc" | "musl";
export type HostedEgress = "none" | "internet";
export type HostedSize = "small" | "medium";
/** Same lifecycle as a store's. */
export type HostedStatus = StoreStatus;

/** Plain (non-secret) environment variables; jsonb. */
export type HostedEnv = ColumnType<Record<string, string>, string | undefined, string>;

export interface HostedServersTable {
  id: Generated<string>;
  slug: string;
  name: string;
  image: string;
  transport: HostedTransport;
  /** stdio: the command the bridge runs; http: optional entrypoint override. */
  command: Generated<string[]>;
  port: Generated<number>;
  path: Generated<string>;
  libc: Generated<HostedLibc>;
  env: HostedEnv;
  /** http only: the variable the image reads its bearer token from (generated by the provisioner). */
  auth_token_env: string | null;
  /** Names only: the values live in the Secret hosted-env-<id>. */
  secret_env_keys: Generated<string[]>;
  egress: Generated<HostedEgress>;
  size: Generated<HostedSize>;
  status: Generated<HostedStatus>;
  step: string | null;
  reason: string | null;
  namespace: string | null;
  server_id: string | null;
  created_by: string | null;
  deadline_at: Date | null;
  created_at: CreatedAt;
  updated_at: Generated<Date>;
}

export interface AuditLogTable {
  id: Generated<string>;
  ts: Generated<Date>;
  user_id: string | null;
  user_email: string;
  api_key_id: string | null;
  source: AuditSource;
  server_slug: string | null;
  tool_name: string;
  duration_ms: number;
  outcome: AuditOutcome;
  error: string | null;
  /** The `X-Request-ID` of the request that made the call; null for older rows. */
  request_id: string | null;
  /** Context that isn't an error, e.g. the query of a `search_tools` call. */
  detail: string | null;
}

export interface SessionsTable {
  id: Generated<string>;
  user_id: string;
  token_hash: Buffer;
  created_at: CreatedAt;
  last_seen_at: Generated<Date>;
  expires_at: Date;
}

export interface InvitesTable {
  id: Generated<string>;
  user_id: string;
  token_hash: Buffer;
  created_by: string | null;
  created_at: CreatedAt;
  expires_at: Date;
  used_at: Date | null;
}

export interface ToolPermissionsTable {
  id: Generated<string>;
  role: Role | null;
  user_id: string | null;
  server_slug: string;
  /** Upstream's own tool name; null = every tool of the server. */
  tool_name: string | null;
  effect: "allow" | "deny";
  created_by: string | null;
  created_at: CreatedAt;
}

export interface WriteApprovalsTable {
  id: Generated<string>;
  user_id: string;
  tool_name: string;
  args: unknown;
  args_hash: string;
  status: Generated<"pending" | "approved" | "denied">;
  created_at: CreatedAt;
  decided_at: Date | null;
  expires_at: Date;
  used_at: Date | null;
}

export interface OAuthClientsTable {
  id: string;
  name: string;
  redirect_uris: string[];
  created_at: CreatedAt;
  last_used_at: Date | null;
}

export interface OAuthRequestsTable {
  id: Generated<string>;
  client_id: string;
  redirect_uri: string;
  state: string | null;
  code_challenge: string;
  scope: string[];
  resource: string;
  created_at: CreatedAt;
  expires_at: Date;
}

export interface OAuthCodesTable {
  hash: Buffer;
  client_id: string;
  user_id: string;
  redirect_uri: string;
  code_challenge: string;
  scope: string[];
  resource: string;
  family_id: string;
  created_at: CreatedAt;
  expires_at: Date;
  used_at: Date | null;
}

export interface OAuthTokensTable {
  id: Generated<string>;
  hash: Buffer;
  kind: "access" | "refresh";
  family_id: string;
  client_id: string;
  user_id: string;
  scope: string[];
  resource: string;
  created_at: CreatedAt;
  expires_at: Date;
  used_at: Date | null;
  last_used_at: Date | null;
  revoked_at: Date | null;
}

export interface Database {
  users: UsersTable;
  api_keys: ApiKeysTable;
  mcp_servers: McpServersTable;
  audit_log: AuditLogTable;
  sessions: SessionsTable;
  invites: InvitesTable;
  tool_permissions: ToolPermissionsTable;
  write_approvals: WriteApprovalsTable;
  stores: StoresTable;
  hosted_servers: HostedServersTable;
  oauth_clients: OAuthClientsTable;
  oauth_requests: OAuthRequestsTable;
  oauth_codes: OAuthCodesTable;
  oauth_tokens: OAuthTokensTable;
}

export type User = Selectable<UsersTable>;
export type UserUpdate = Updateable<UsersTable>;
export type NewUser = Insertable<UsersTable>;
export type ApiKey = Selectable<ApiKeysTable>;
export type McpServer = Selectable<McpServersTable>;
export type NewMcpServer = Insertable<McpServersTable>;
export type McpServerUpdate = Updateable<McpServersTable>;
export type ToolPermissionRow = Selectable<ToolPermissionsTable>;
export type WriteApproval = Selectable<WriteApprovalsTable>;
export type AuditEntry = Selectable<AuditLogTable>;
export type NewAuditEntry = Insertable<AuditLogTable>;
export type Store = Selectable<StoresTable>;
export type NewStore = Insertable<StoresTable>;
export type StoreUpdate = Updateable<StoresTable>;
export type HostedServer = Selectable<HostedServersTable>;
export type NewHostedServer = Insertable<HostedServersTable>;
export type HostedServerUpdate = Updateable<HostedServersTable>;
export type OAuthClient = Selectable<OAuthClientsTable>;
export type OAuthRequest = Selectable<OAuthRequestsTable>;
